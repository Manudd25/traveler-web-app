import { jsPDF } from "jspdf";
import {
  formatCurrencyExact,
  formatDateRange,
  getBudgetSummary,
  getReadiness,
  groupItineraryByDay,
  tripDurationDays,
} from "./tripHelpers";

export function exportTripPdf(trip) {
  if (!trip) return;

  const doc = new jsPDF();
  const margin = 14;
  let y = 18;
  const line = (text, size = 11, style = "normal") => {
    if (y > 280) {
      doc.addPage();
      y = 18;
    }
    doc.setFont("helvetica", style);
    doc.setFontSize(size);
    const lines = doc.splitTextToSize(String(text ?? ""), 180);
    doc.text(lines, margin, y);
    y += lines.length * (size * 0.45) + 4;
  };

  const budget = getBudgetSummary(trip);
  const readiness = getReadiness(trip.checklist);
  const days = tripDurationDays(trip.startDate, trip.endDate);

  line("Traveler — Trip Summary", 18, "bold");
  line(trip.destination || "Untitled trip", 14, "bold");
  line(formatDateRange(trip.startDate, trip.endDate));
  line(`${days} days · ${trip.travelers} traveler${trip.travelers === 1 ? "" : "s"}`);
  line(`Readiness: ${readiness}%`);
  y += 4;

  line("Budget", 13, "bold");
  line(
    `Spent ${formatCurrencyExact(budget.spent, budget.currency)} of ${formatCurrencyExact(budget.total, budget.currency)} · Remaining ${formatCurrencyExact(budget.remaining, budget.currency)}`
  );
  y += 2;

  line("Itinerary", 13, "bold");
  const groups = groupItineraryByDay(trip.itinerary);
  if (!groups.length) {
    line("No itinerary items yet.");
  } else {
    groups.forEach((g) => {
      line(`DAY ${g.day} — ${(g.dayLabel || "").toUpperCase()}`, 12, "bold");
      g.items.forEach((item) => {
        line(
          `${item.time || "--:--"}  ${item.title}${item.location ? ` · ${item.location}` : ""}${item.price ? ` · €${item.price}` : ""}`
        );
      });
      y += 2;
    });
  }

  line("Reservations", 13, "bold");
  if (!(trip.bookings || []).length) {
    line("No bookings yet.");
  } else {
    trip.bookings.forEach((b) => {
      const detail =
        b.type === "cinema"
          ? `${b.title} · seats ${(b.details?.seats || []).join(", ")} · ${b.details?.showTime || ""}`
          : b.type === "restaurant"
            ? `${b.title} · table ${b.details?.tableId || ""} · ${b.details?.guests || ""} guests`
            : `${b.title} · ${b.details?.language || ""} · ${b.details?.time || ""} · ${b.details?.participants || ""} pax`;
      line(`${b.type?.toUpperCase()} — ${detail} · €${Number(b.totalPrice || 0).toFixed(2)}`);
    });
  }
  y += 2;

  line("Checklist", 13, "bold");
  (trip.checklist || []).forEach((c) => {
    line(`${c.completed ? "[x]" : "[ ]"} ${c.label}`);
  });

  y += 6;
  line("Generated by Traveler · Demo bookings are simulations only.", 9);

  const safeName = (trip.destination || "trip").replace(/[^a-z0-9]+/gi, "-").toLowerCase();
  doc.save(`${safeName}-summary.pdf`);
}
